import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ml_dsa44 } from "@noble/post-quantum/ml-dsa.js";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../contracts/test/generated");
mkdirSync(outDir, { recursive: true });

// Deterministic test key. NEVER use this seed for anything real.
const seed = new Uint8Array(32).fill(7);
const { publicKey, secretKey } = ml_dsa44.keygen(seed);

const digest = new Uint8Array(32).fill(0x42);
const signature = ml_dsa44.sign(digest, secretKey);

if (!ml_dsa44.verify(signature, digest, publicKey)) {
  throw new Error("generated signature does not verify");
}

const hex = (bytes) => "0x" + Buffer.from(bytes).toString("hex");

const solidity = `// SPDX-License-Identifier: MIT
// AUTO-GENERATED by scripts/gen-mldsa-fixture.mjs. Do not edit by hand.
pragma solidity ^0.8.24;

library MLDSA44Vector {
    bytes32 internal constant DIGEST = ${hex(digest)};
    bytes internal constant PUBLIC_KEY = hex"${Buffer.from(publicKey).toString("hex")}";
    bytes internal constant SIGNATURE = hex"${Buffer.from(signature).toString("hex")}";
}
`;

writeFileSync(resolve(outDir, "MLDSA44Vector.sol"), solidity);
writeFileSync(
  resolve(here, "../contracts/test/fixtures/mldsa44.json"),
  JSON.stringify({ digest: hex(digest), publicKey: hex(publicKey), signature: hex(signature) }, null, 2)
);

console.log(`publicKey ${publicKey.length} bytes`);
console.log(`signature ${signature.length} bytes`);
console.log(`wrote ${resolve(outDir, "MLDSA44Vector.sol")}`);
